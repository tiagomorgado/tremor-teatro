import { forwardRef, type CSSProperties } from "react";
import { getMedia, mediaUrl, pickWidth, srcSet } from "~/data/media";

type Props = {
  src: string;
  alt: string;
  sizes?: string;
  /** Above-the-fold images: eager + high fetch priority (LCP). */
  priority?: boolean;
  className?: string;
  imgClassName?: string;
  style?: CSSProperties;
  /** Override the crop point. By default every image uses its detected focal point
   *  (faces first), so subjects stay in frame on tall phone crops and wide banners alike. */
  position?: string;
  /** Fill the parent (absolute, object-cover) instead of using intrinsic ratio. */
  fill?: boolean;
  /** Letterbox instead of crop (lightbox). */
  contain?: boolean;
};

/**
 * Responsive <picture> with AVIF + WebP sources generated by scripts/optimize-media.mjs.
 * A 20px blurred placeholder is painted underneath until the real image arrives, and
 * width/height are always set so the layout never shifts. No JS needed to reveal it.
 */
export const Img = forwardRef<HTMLImageElement, Props>(function Img(
  { src, alt, sizes = "100vw", priority, className = "", imgClassName = "", style, position, fill, contain },
  ref,
) {
  const m = getMedia(src);
  const focus = position ?? m.focus ?? "center";
  const fallback = mediaUrl(src, pickWidth(src, 1280), "webp");

  return (
    <picture
      className={`${fill ? "absolute inset-0" : "relative"} block overflow-hidden ${className}`}
      style={{
        ...(fill ? {} : { aspectRatio: `${m.w} / ${m.h}` }),
        backgroundImage: m.lqip && !contain ? `url(${m.lqip})` : undefined,
        backgroundSize: "cover",
        backgroundPosition: focus,
        ...style,
      }}
    >
      {!m.logo && <source type="image/avif" srcSet={srcSet(src, "avif")} sizes={sizes} />}
      <source type="image/webp" srcSet={srcSet(src, "webp")} sizes={sizes} />
      <img
        ref={ref}
        src={fallback}
        alt={alt}
        width={m.w}
        height={m.h}
        sizes={sizes}
        loading={priority ? "eager" : "lazy"}
        decoding="async"
        fetchPriority={priority ? "high" : undefined}
        className={`h-full w-full ${contain ? "object-contain" : "object-cover"} ${imgClassName}`}
        style={{ objectPosition: focus }}
        draggable={false}
      />
    </picture>
  );
});
